#!/usr/bin/env python3
"""Unlabeled recalibration baseline using only target benign traffic.

This tests whether benign-only threshold reselection materially improves the
transferred operating point once the frozen source threshold is applied on the
target domain.

The recalibration uses ONLY target benign traffic (label=0), NOT target
attacks. The target benign pool is partitioned deterministically into a
calibration split for threshold selection and a disjoint evaluation split for
the realized held-out benign FPR estimate. This is operationally realistic: a
short 'clean' deployment window or a known-benign traffic sample is available
in many practical deployments.
"""
from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import pandas as pd

from iot_ids.recalibration import DEFAULT_RECALIBRATION_SEED, run_unlabeled_recalibration

DATASET_SHORT = {
    "iot23": "I23",
    "ton_iot": "TON",
    "unsw_nb15": "UNSW",
}

MODEL_LABELS = {
    "logistic_regression": "LR",
    "extra_trees": "ET",
    "hist_gradient_boosting": "HGB",
    "mlp": "MLP",
    "ft_transformer": "FTT",
}

DIRECTION_ORDER = [
    ("iot23", "ton_iot"),
    ("iot23", "unsw_nb15"),
    ("ton_iot", "iot23"),
    ("ton_iot", "unsw_nb15"),
    ("unsw_nb15", "iot23"),
    ("unsw_nb15", "ton_iot"),
]

MODEL_ORDER = [
    "logistic_regression",
    "extra_trees",
    "hist_gradient_boosting",
    "mlp",
    "ft_transformer",
]


def _load_prediction_groups(
    path: str, chunksize: int = 500000
) -> dict[tuple[str, str], pd.DataFrame]:
    """Load predictions grouped by (setting_id, eval_role)."""
    grouped_chunks: dict[tuple[str, str], list[pd.DataFrame]] = defaultdict(list)
    for chunk in pd.read_csv(
        path,
        usecols=["setting_id", "eval_role", "record_id", "group_id", "label", "score"],
        chunksize=chunksize,
    ):
        for (sid, role), sub in chunk.groupby(["setting_id", "eval_role"], sort=False):
            grouped_chunks[(str(sid), str(role))].append(
                sub[["record_id", "group_id", "label", "score"]].reset_index(drop=True)
            )
    return {
        key: pd.concat(parts, ignore_index=True)
        for key, parts in grouped_chunks.items()
    }


def _format_metric(value: float) -> str:
    return f"{float(value):.3f}"


def _format_eval_fpr(value: float) -> str:
    return f"{float(value):.4f}"


def _direction_label(source_dataset: str, target_dataset: str) -> str:
    return f"{DATASET_SHORT[source_dataset]}$\\to${DATASET_SHORT[target_dataset]}"


def write_acsac_table(result: pd.DataFrame, output_path: Path) -> None:
    direction_order = {pair: index for index, pair in enumerate(DIRECTION_ORDER)}
    model_order = {model: index for index, model in enumerate(MODEL_ORDER)}
    frame = result.copy()
    frame["direction"] = frame.apply(
        lambda row: _direction_label(str(row["source_dataset"]), str(row["target_dataset"])),
        axis=1,
    )
    frame["direction_order"] = frame.apply(
        lambda row: direction_order[(str(row["source_dataset"]), str(row["target_dataset"]))],
        axis=1,
    )
    frame["model_order"] = frame["model"].map(model_order)
    frame["model_label"] = frame["model"].map(MODEL_LABELS)
    frame = frame.sort_values(["direction_order", "model_order"]).reset_index(drop=True)

    lines = [
        "% Generated by scripts/46_unlabeled_recalibration.py",
        r"\begin{table}[!htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3.5pt}",
        rf"\caption{{Per-setting benign-only recalibration at \FrozenFprTarget{{}} FPR using only a target-benign calibration split (no attack labels). Recal TPR is measured on the full target attack set, while Eval FPR is measured on a disjoint held-out target-benign evaluation split and printed to four decimals so exceedances just above the \FrozenFprTarget{{}} budget remain visible. Rows are grouped by transfer direction. The final row reports the mean across all \NaturalSettingCount{{}} settings.}}",
        r"\label{tab:acsac-recalibration}",
        r"\begin{tabular}{llrrrr}",
        r"\toprule",
        r"Direction & Model & Target AUROC & Frozen TPR & Recal TPR & Eval FPR \\",
        r"\midrule",
    ]

    current_direction = None
    for row in frame.itertuples(index=False):
        if current_direction is not None and row.direction != current_direction:
            lines.append(r"\midrule")
        current_direction = row.direction
        lines.append(
            f"{row.direction} & {row.model_label} & {_format_metric(row.target_auroc)} & "
            f"{_format_metric(row.frozen_tpr)} & {_format_metric(row.recal_tpr)} & "
            f"{_format_eval_fpr(row.recal_fpr)} \\\\"
        )

    lines.extend(
        [
            r"\midrule",
            rf"\emph{{Mean ({len(result)})}} & -- & "
            f"{_format_metric(result['target_auroc'].mean())} & "
            f"{_format_metric(result['frozen_tpr'].mean())} & "
            f"{_format_metric(result['recal_tpr'].mean())} & "
            f"{_format_eval_fpr(result['recal_fpr'].mean())} \\\\",
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Run unlabeled recalibration baseline using target benign traffic."
    )
    parser.add_argument("--settings", default="artifacts/benchmark/settings.csv")
    parser.add_argument("--predictions", default="artifacts/benchmark/predictions.csv")
    parser.add_argument("--output-dir", default="artifacts/recalibration")
    parser.add_argument("--calibration-frac", type=float, default=0.5)
    parser.add_argument("--seed", type=int, default=DEFAULT_RECALIBRATION_SEED)
    args = parser.parse_args()

    settings = pd.read_csv(args.settings)
    print("Loading predictions...", flush=True)
    prediction_groups = _load_prediction_groups(args.predictions)
    print(f"Loaded {len(prediction_groups)} groups.", flush=True)

    result = run_unlabeled_recalibration(
        settings,
        prediction_groups,
        target_fpr=0.01,
        calibration_frac=float(args.calibration_frac),
        seed=int(args.seed),
    )

    print("\n=== Unlabeled Recalibration Summary ===")
    summary = result.groupby("recal_diagnosis").agg(
        count=("setting_id", "count"),
        mean_target_auroc=("target_auroc", "mean"),
        mean_frozen_tpr=("frozen_tpr", "mean"),
        mean_recal_tpr=("recal_tpr", "mean"),
        mean_oracle_tpr=("oracle_tpr", "mean"),
        mean_eval_fpr=("recal_fpr", "mean"),
        mean_tpr_recovery=("tpr_recovery", "mean"),
    )
    print(summary.to_string())

    print("\n=== By Direction ===")
    direction_summary = result.groupby(
        ["source_dataset", "target_dataset"]
    ).agg(
        mean_frozen_tpr=("frozen_tpr", "mean"),
        mean_recal_tpr=("recal_tpr", "mean"),
        mean_oracle_tpr=("oracle_tpr", "mean"),
        mean_eval_fpr=("recal_fpr", "mean"),
        mean_target_auroc=("target_auroc", "mean"),
    )
    print(direction_summary.to_string())

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    result.to_csv(output_dir / "unlabeled_recalibration.csv", index=False)
    write_acsac_table(result, Path("paper/acsac/tables/recalibration.tex"))
    print(f"\nWrote {len(result)} rows to {output_dir / 'unlabeled_recalibration.csv'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
