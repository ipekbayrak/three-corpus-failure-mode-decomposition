from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pandas as pd

from iot_ids.data import RAW_REQUIRED_COLUMNS, load_dataset_specs, load_staged_dataset
from iot_ids.features import FEATURE_APPENDIX_ROWS, FEATURE_SCHEMA_VERSION
from iot_ids.staging import SCHEMA_APPENDIX_MAPPING_RULES

DATASET_ORDER = ["iot23", "ton_iot", "unsw_nb15"]

DATASET_LABELS = {
    "iot23": "IoT-23",
    "ton_iot": "ToN-IoT",
    "unsw_nb15": "UNSW-NB15",
}


@dataclass(frozen=True)
class SchemaAppendixOutputs:
    feature_schema_csv: Path
    raw_mapping_csv: Path
    discarded_columns_csv: Path
    journal_feature_table: Path
    acsac_feature_table: Path


def _write_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _escape_latex_text(value: object) -> str:
    text = str(value)
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("_", r"\_")
        .replace("%", r"\%")
        .replace("&", r"\&")
        .replace("#", r"\#")
        .replace("{", r"\{")
        .replace("}", r"\}")
    )


def _tabular(
    frame: pd.DataFrame,
    alignment: str,
) -> str:
    header = " & ".join(frame.columns) + r" \\"
    rows = [" & ".join(map(str, row)) + r" \\" for row in frame.itertuples(index=False, name=None)]
    return "\n".join(
        [
            rf"\begin{{tabular}}{{{alignment}}}",
            r"\toprule",
            header,
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
        ]
    )


def _wrap_table(
    tabular: str,
    caption: str,
    label: str,
    font_size: str,
    environment: str = "table*",
    resize: bool = False,
    arraystretch: float | None = None,
) -> str:
    body = tabular
    if resize:
        body = "\n".join(
            [
                r"\resizebox{\textwidth}{!}{%",
                body,
                r"}",
            ]
        )
    return "\n".join(
        [
            "% Generated by src/iot_ids/schema_appendix.py",
            rf"\begin{{{environment}}}[t]",
            r"\centering",
            font_size,
            *(
                [rf"\renewcommand{{\arraystretch}}{{{arraystretch:.2f}}}"]
                if arraystretch is not None
                else []
            ),
            r"\setlength{\tabcolsep}{4pt}",
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
            body,
            rf"\end{{{environment}}}",
            "",
        ]
    )


def _linebreak_text(
    value: object,
    *,
    break_after: tuple[str, ...] = (),
    break_before: tuple[str, ...] = (),
) -> str:
    marker = "<LB>"
    text = str(value)
    for token in break_after:
        text = text.replace(token, token + marker)
    for token in break_before:
        replacement = token.strip()
        if token.startswith(" "):
            replacement = " " + replacement
        text = text.replace(token, marker + replacement + " ")
    lines = [_escape_latex_text(part.strip()) for part in text.split(marker) if part.strip()]
    if len(lines) <= 1:
        return lines[0] if lines else ""
    return r"\begin{tabular}[t]{@{}l@{}}" + r" \\ ".join(lines) + r"\end{tabular}"


def _stacked_lines(lines: list[str]) -> str:
    escaped = [_escape_latex_text(line) for line in lines if line]
    if len(escaped) <= 1:
        return escaped[0] if escaped else ""
    return r"\begin{tabular}[t]{@{}l@{}}" + r" \\ ".join(escaped) + r"\end{tabular}"


def _feature_name_text(value: object) -> str:
    text = str(value)
    parts = text.split("_")
    if len(parts) <= 2:
        return _escape_latex_text(text)
    pivot = (len(parts) + 1) // 2
    return _stacked_lines([f"{'_'.join(parts[:pivot])}_", "_".join(parts[pivot:])])


def _feature_schema_frame() -> pd.DataFrame:
    frame = pd.DataFrame(FEATURE_APPENDIX_ROWS).copy()
    return frame.rename(
        columns={
            "feature_name": "feature_name",
            "definition": "definition",
            "derived_from": "derived_from",
        }
    )


def _raw_mapping_frame() -> pd.DataFrame:
    rows = []
    for primitive_field in RAW_REQUIRED_COLUMNS:
        rows.append(
            {
                "primitive_field": primitive_field,
                "iot23": SCHEMA_APPENDIX_MAPPING_RULES["iot23"][primitive_field],
                "ton_iot": SCHEMA_APPENDIX_MAPPING_RULES["ton_iot"][primitive_field],
                "unsw_nb15": SCHEMA_APPENDIX_MAPPING_RULES["unsw_nb15"][primitive_field],
            }
        )
    return pd.DataFrame(rows)


def _discarded_columns_frame(config: dict[str, Any]) -> pd.DataFrame:
    specs = load_dataset_specs(config)
    rows = []
    for dataset_name in DATASET_ORDER:
        spec = specs[dataset_name]
        frame = load_staged_dataset(spec)
        discarded = sorted(
            column
            for column in frame.columns
            if column not in set(RAW_REQUIRED_COLUMNS).union({"dataset"})
        )
        rows.append(
            {
                "dataset": DATASET_LABELS[dataset_name],
                "discarded_source_columns": ", ".join(discarded) if discarded else "none",
            }
        )
    return pd.DataFrame(rows)


def _feature_schema_table(frame: pd.DataFrame, font_size: str) -> str:
    schema_version = _escape_latex_text(FEATURE_SCHEMA_VERSION.replace("_", " "))
    working = frame.rename(
        columns={
            "feature_name": "Feature",
            "definition": "Formula",
            "derived_from": "Derived From",
        }
    ).copy()
    working["Feature"] = working["Feature"].map(_feature_name_text)
    working["Formula"] = working["Formula"].map(
        lambda value: _linebreak_text(
            value,
            break_after=("; ", " + "),
            break_before=(" / ",),
        )
    )
    working["Derived From"] = working["Derived From"].map(
        lambda value: _linebreak_text(value, break_after=(", ",))
    )
    protocol_mask = frame["feature_name"].astype(str).str.startswith("proto_")
    quantitative = working.loc[~protocol_mask].reset_index(drop=True)
    return _wrap_table(
        _tabular(
            quantitative,
            alignment=r"p{0.22\columnwidth}p{0.42\columnwidth}p{0.18\columnwidth}",
        ),
        (
            r"Shared-schema quantitative features used in the canonical "
            rf"benchmark ({schema_version})."
        ),
        "tab:shared-feature-schema-quantitative",
        font_size=font_size,
        environment="table",
        arraystretch=1.08,
    )


def _raw_mapping_table(frame: pd.DataFrame, font_size: str) -> str:
    schema_version = _escape_latex_text(FEATURE_SCHEMA_VERSION.replace("_", " "))
    tables: list[str] = []
    for dataset_name in DATASET_ORDER:
        panel = frame[["primitive_field", dataset_name]].rename(
            columns={
                "primitive_field": "Primitive Field",
                dataset_name: "Raw field(s) / rule",
            }
        )
        panel["Primitive Field"] = panel["Primitive Field"].map(_escape_latex_text)
        panel["Raw field(s) / rule"] = panel["Raw field(s) / rule"].map(
            lambda value: _linebreak_text(
                value,
                break_after=(", ", " / "),
                break_before=(" fallback ", " or "),
            )
        )
        tabular = _tabular(panel, alignment=r"p{0.25\textwidth}p{0.65\textwidth}")
        tables.append(
            _wrap_table(
                tabular,
                (
                    r"Raw-to-primitive mapping rules for "
                    rf"{_escape_latex_text(DATASET_LABELS[dataset_name])} before "
                    rf"{schema_version}."
                ),
                f"tab:raw-to-primitive-mapping-{dataset_name.replace('_', '-')}",
                font_size=font_size,
                arraystretch=1.10,
            )
        )
    return "\n".join(tables)


def _discarded_columns_table(frame: pd.DataFrame, font_size: str) -> str:
    schema_version = _escape_latex_text(FEATURE_SCHEMA_VERSION)
    working = frame.rename(
        columns={
            "dataset": "Dataset",
            "discarded_source_columns": "Discarded Source Columns",
        }
    ).copy()
    working["Dataset"] = working["Dataset"].map(_escape_latex_text)
    working["Discarded Source Columns"] = working["Discarded Source Columns"].map(
        lambda value: _linebreak_text(value, break_after=(", ",))
    )
    tabular = _tabular(working, alignment=r"p{0.18\textwidth}p{0.68\textwidth}")
    return _wrap_table(
        tabular,
        (
            r"Source-side staged columns that are discarded before "
            rf"{schema_version}. They are retained for staging or "
            r"provenance only and never enter the shared flow-level model input."
        ),
        "tab:discarded-source-columns",
        font_size=font_size,
        environment="table*",
        arraystretch=1.15,
    )


def write_schema_appendix_assets(
    config: dict[str, Any],
    outputs: SchemaAppendixOutputs,
) -> dict[str, int]:
    feature_frame = _feature_schema_frame()
    mapping_frame = _raw_mapping_frame()
    discarded_frame = _discarded_columns_frame(config)

    for path in [
        outputs.feature_schema_csv,
        outputs.raw_mapping_csv,
        outputs.discarded_columns_csv,
    ]:
        path.parent.mkdir(parents=True, exist_ok=True)
    feature_frame.to_csv(outputs.feature_schema_csv, index=False)
    mapping_frame.to_csv(outputs.raw_mapping_csv, index=False)
    discarded_frame.to_csv(outputs.discarded_columns_csv, index=False)

    _write_text(
        outputs.journal_feature_table,
        _feature_schema_table(feature_frame, r"\footnotesize"),
    )
    _write_text(
        outputs.acsac_feature_table,
        _feature_schema_table(feature_frame, r"\scriptsize"),
    )

    return {
        "feature_rows": int(len(feature_frame)),
        "mapping_rows": int(len(mapping_frame)),
        "discarded_rows": int(len(discarded_frame)),
    }
